def gazebo_world_sdf(scene: FloodScene, out: Optional[Path] = None,
                     max_houses: int = 60) -> str:
    """Render the flood town as a Gazebo SDF world string (and file)."""
    parts = [_SDF_HEAD]
    half = scene.size_m / 2.0
    parts.append(f"""
    <model name="ground"><static>true</static>
      <link name="l"><collision name="c">
        <geometry><plane><normal>0 0 1</normal>
          <size>{scene.size_m * 1.6} {scene.size_m * 1.6}</size></plane></geometry>
      </collision><visual name="v">
        <geometry><plane><normal>0 0 1</normal>
          <size>{scene.size_m * 1.6} {scene.size_m * 1.6}</size></plane></geometry>
        <material><diffuse>0.42 0.40 0.36 1</diffuse></material>
      </visual></link></model>
    <model name="flood_water"><static>true</static>
      <pose>0 0 {scene.water_level_m} 0 0 0</pose>
      <link name="l"><visual name="v">
        <geometry><plane><normal>0 0 1</normal>
          <size>{scene.size_m * 1.2} {scene.size_m * 1.2}</size></plane></geometry>
        <material><diffuse>0.26 0.36 0.44 0.82</diffuse></material>
      </visual></link></model>""")
    for i, h in enumerate(scene.houses[:max_houses]):
        parts.append(f"""
    <model name="house_{i:02d}"><static>true</static>
      <pose>{-h.e:.2f} {-h.n:.2f} {h.h_m / 2:.2f} 0 0 0</pose>
      <link name="l">
        <visual name="walls"><pose>0 0 0 0 0 0</pose>
          <geometry><box><size>{h.w_m} {h.d_m} {h.h_m}</size></box></geometry>
          <material><diffuse>0.62 0.58 0.52 1</diffuse></material></visual>
        <visual name="roof"><pose>0 0 {h.h_m / 2 + 0.4:.2f} 0 0 0</pose>
          <geometry><box><size>{h.w_m + 0.6:.1f} {h.d_m + 0.6:.1f} 0.25</size></box></geometry>
          <material><diffuse>0.59 0.55 0.51 1</diffuse></material></visual>
        <sensor name="t" type="thermal_camera"/>  <!-- inherits link temp -->
      </link></model>""")
    for i, s in enumerate(scene.survivors):
        z = scene.water_level_m + (0.4 if s.in_water else (3.6 if s.on_roof else 0.5))
        parts.append(f"""
    <model name="victim_{s.sid}"><static>true</static>
      <pose>{-s.e:.2f} {-s.n:.2f} {z:.2f} 0 0 0</pose>
      <link name="l"><visual name="v">
        <geometry><capsule><radius>0.22</radius><length>0.9</length></capsule></geometry>
        <material><diffuse>{s.clothing[0]/255:.2f} {s.clothing[1]/255:.2f} {s.clothing[2]/255:.2f} 1</diffuse></material>
      </visual></link></model>""")
    parts.append(_UAV_SDF)
    parts.append(_SDF_TAIL)
    sdf = "\n".join(parts)
    if out is not None:
        out = Path(out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(sdf)
    return sdf


def gazebo_launch_hint(world_path: str = "worlds/flood_town/flood_town.sdf") -> str:
    return (
        "# Terminal 1 — Gazebo flood town:\n"
        f"  gz sim {world_path} -r\n"
        "# Terminal 2 — ArduPilot SITL bound to it (or MiniSITL fallback):\n"
        "  sim_vehicle.py -v ArduCopter -f gazebo-iris --console --map\n"
        "# Terminal 3 — the flood sortie against live MAVLink:\n"
        "  python3 scripts/run_flood_sim.py --backend gazebo --duration 300\n")


