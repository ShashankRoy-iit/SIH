"""Gazebo bridge: physics + ArduPilot-native flood-town sorties.

Target stack (lab machine):

* **Gazebo Harmonic (gz-sim 8)** + ArduPilot SITL via MAVLink
  (``arducopter --model gazebo-iris`` or the ``gazebo`` backend), ROS 2
  optional — this bridge speaks plain MAVLink + gz-transport CLI topics, so
  it works with or without a ROS install.
* This repo's flood town as SDF: ``worlds/flood_town/flood_town.sdf``,
  generated from ``sar/sim/flood_scene.py`` by :func:`gazebo_world_sdf` so
  all three backends share one town.

Sensor mapping in the SDF world:

* RGB camera (1280x720 @15) + depth camera + **thermal camera plugin**
  (``gz::sim::systems::ThermalCamera``, per-link temperatures) — Gazebo is
  the only backend here with a *native* LWIR sensor model.
* GPU LiDAR (16-channel, 12 m) + IMU + GPS + barometer + magnetometer.
* Water surface: semi-transparent plane + buoyancy plugin hooks for future
  floating-victim drift.

Like the AirSim bridge, everything here degrades cleanly: :func:`gazebo_available`
probes for ``gz`` / ``ign`` binaries and the ArduPilot SITL binary, and the
flood runner falls through to headless when they are absent.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

from sar.sim.flood_scene import FloodScene


def gazebo_available() -> Tuple[bool, str]:
    gz = shutil.which("gz") or shutil.which("ign")
    if gz is None:
        return False, "no `gz`/`ign` binary on PATH (install Gazebo Harmonic)"
    sitl = shutil.which("arducopter") or shutil.which("arducopter-sitl")
    extra = " + arducopter SITL" if sitl else " (ArduPilot SITL not found; MiniSITL fallback)"
    try:
        out = subprocess.run([gz, "sim", "--versions"], capture_output=True,
                             text=True, timeout=10)
        ver = (out.stdout or out.stderr).strip().splitlines()
        ver = ver[0][:60] if ver else "unknown version"
    except Exception as exc:
        return False, f"`gz` present but not runnable ({exc})"
    return True, f"{gz} ({ver}){extra}"


